#[cfg(test)]
mod tests {
    use super::Mnemonic;

    /// Each mnemonic's name is the one it is declared with.
    #[test]
    fn names_are_as_declared() {
        assert_eq!(Mnemonic::ALL.len(), super::LIST.len());
        for (m, name) in Mnemonic::ALL.iter().zip(super::LIST) {
            assert_eq!(m.name(), *name);
        }
        assert_eq!(Mnemonic::Addi.name(), "addi");
        assert_eq!(Mnemonic::CLw.name(), "c.lw");
        assert_eq!(Mnemonic::Illegal.name(), ".insn");
    }

    /// Each mnemonic has its own name.
    #[test]
    fn names_are_unique() {
        let mut names: [&str; Mnemonic::ALL.len()] = [""; Mnemonic::ALL.len()];
        for (slot, m) in names.iter_mut().zip(Mnemonic::ALL) {
            *slot = m.name();
        }
        names.sort_unstable();
        for pair in names.windows(2) {
            assert_ne!(pair[0], pair[1]);
        }
    }
}
