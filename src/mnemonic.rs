//! The mnemonic of an instruction, as a type.

/// Declares [`Mnemonic`] with one variant per mnemonic and the name of each.
macro_rules! mnemonics {
    ($($(#[$attr:meta])* $variant:ident = $name:literal,)*) => {
        /// The mnemonic of an instruction or pseudoinstruction, such as
        /// [`Mnemonic::Addi`] for `addi` or [`Mnemonic::CLw`] for `c.lw`.
        ///
        /// [`Instruction::id`](crate::Instruction::id) gives the mnemonic an
        /// instruction is shown with, and
        /// [`without_aliases`](crate::Instruction::without_aliases) the one it
        /// is encoded as. Each variant is named after its mnemonic in camel
        /// case, a `.` or `_` starting a new word (`fcvt.d.wu` is
        /// [`Mnemonic::FcvtDWu`]); an encoding that is not a valid instruction
        /// is [`Mnemonic::Illegal`] (`.insn`), and a parcel of a reserved-length
        /// encoding [`Mnemonic::ReservedParcel`] (`.2byte`). The vector and
        /// vendor mnemonics exist only with the Cargo features that decode
        /// them.
        #[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
        #[non_exhaustive]
        pub enum Mnemonic {
            $(
                #[doc = concat!("`", $name, "`")]
                $(#[$attr])*
                $variant,
            )*
        }

        /// Every name, in the order of the variants. Only the build reads
        /// it: the binary keeps [`TEXT`] and [`STARTS`].
        const LIST: &[&str] = &[$($(#[$attr])* $name,)*];

        impl Mnemonic {
            /// The mnemonic as text, such as `"addi"` or `"c.lw"`: what
            /// [`Instruction::mnemonic`](crate::Instruction::mnemonic) returns.
            pub fn name(self) -> &'static str {
                let i = self as usize;
                match (STARTS.get(i), STARTS.get(i + 1)) {
                    (Some(&start), Some(&end)) => {
                        TEXT.get(start as usize..end as usize).unwrap_or_default()
                    }
                    _ => "",
                }
            }

            /// Every mnemonic, in declaration order.
            #[cfg(test)]
            pub(crate) const ALL: &[Mnemonic] = &[$($(#[$attr])* Self::$variant,)*];
        }
    };
}

/// The names end to end, so that a name costs its text and one offset
/// rather than a pointer and a length.
static TEXT: &str = match core::str::from_utf8(&TEXT_BYTES) {
    Ok(text) => text,
    Err(_) => panic!("a mnemonic is not UTF-8"),
};

const TEXT_BYTES: [u8; text_len(LIST)] = text(LIST);

/// Where each name starts in [`TEXT`], and then where the last one ends.
static STARTS: [u16; LIST.len() + 1] = starts(LIST);

const fn text_len(list: &[&str]) -> usize {
    let mut len = 0;
    let mut i = 0;
    while i < list.len() {
        len += list[i].len();
        i += 1;
    }
    len
}

const fn text<const N: usize>(list: &[&str]) -> [u8; N] {
    let mut text = [0; N];
    let mut at = 0;
    let mut i = 0;
    while i < list.len() {
        let name = list[i].as_bytes();
        let mut j = 0;
        while j < name.len() {
            text[at] = name[j];
            at += 1;
            j += 1;
        }
        i += 1;
    }
    text
}

const fn starts<const N: usize>(list: &[&str]) -> [u16; N] {
    assert!(
        text_len(list) <= u16::MAX as usize,
        "the names outgrow a u16 offset"
    );
    let mut starts = [0; N];
    let mut at = 0;
    let mut i = 0;
    while i < list.len() {
        starts[i] = at as u16;
        at += list[i].len();
        i += 1;
    }
    starts[list.len()] = at as u16;
    starts
}

// `Debug` shows the name, as `Display` does: a derived `Debug` would add a
// second table of every variant's name to the binary.
impl core::fmt::Debug for Mnemonic {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.write_str(self.name())
    }
}

impl core::fmt::Display for Mnemonic {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.write_str(self.name())
    }
}

